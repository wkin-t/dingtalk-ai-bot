# -*- coding: utf-8 -*-
"""/help 命令的命令清单渲染，按场景分组。"""
from app.config import BOT_ID


def render_help() -> str:
    """生成当前 agent 可用命令清单（按分组）。"""
    return f"""## 📖 命令帮助（{BOT_ID}）

我支持以下命令——直接在对话里发，**对每个 agent 独立生效**。

---

### 🧹 上下文管理

| 命令 | 作用 |
|------|------|
| `/clear` | 软清空：仅当前 agent 看不到此刻之前的历史，**不影响其他 agent**。其他写法：`清空上下文` / `🧹 清空记忆` |
| `/since` | 显示我能看到的最早一条消息的时间 + 当前 cutoff（用于定位上下文起点） |

> 软清空只记录时间戳，不删数据库。其他 agent 仍能看到完整历史。

---

### 🎭 Soul 个性（仅群聊）

| 命令 | 作用 |
|------|------|
| `/soul` | 查看当前 Soul 配置（含进化状态） |
| `/soul 你的设定` | 设置群专属 Soul（需管理员） |
| `/soul reset` | 重置为默认 Soul（需管理员） |
| `/soul evolve` | 手动触发 Soul 进化（需管理员） |
| `/soul log` | 查看 Soul 进化历史 |

---

### ⚙️ 采样调参（影响回复风格）

| 命令 | 作用 |
|------|------|
| `/temp` | 查看当前温度配置 + 介绍 |
| `/temp 1.5` | 手动设置温度（范围 0.0–2.0，24h 后自动失效） |
| `/temp reset` | 清除手动温度，回归路由自动 |
| `/top_p` | 查看当前 top_p 配置 + 介绍 |
| `/top_p 0.9` | 手动设置 top_p（范围 0.01–1.0） |
| `/top_p reset` | 清除手动 top_p |
| `/sample` | 查看采样综合视图（含设置人、过期时间） |
| `/sample reset` | 一键清空温度 + top_p 手动设置 |
| `/sample reset temp` | 仅清温度 |
| `/sample reset top_p` | 仅清 top_p |

> 温度高 → 更随机/有创意；top_p 低 → 候选更聚焦。Claude 模型上限 1.0（超过自动 clamp）。

---

### 📊 统计

| 命令 | 作用 |
|------|------|
| `/stats` | 查看当前用户/会话的 token 用量与费用统计 |

---

### ❓ 帮助

| 命令 | 作用 |
|------|------|
| `/help` | 显示本命令清单 |

---

**Tips**：
- 群里艾特机器人后再发命令更稳；私聊直接发命令
- 命令开头的 `/` 不可省略
- 设置温度/top_p 后，群里其他人发消息也会用同样配置（共享 session 维度）
"""
